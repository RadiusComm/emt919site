// Deterministic shared shell, accessibility hygiene and local-import bundling.
// No dependencies or network requests. Run from any directory with Node.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const write = (file, value) => fs.writeFileSync(path.join(root, file), value);
const header = read('site-components/header.html').trim();
const footer = read('site-components/footer.html').trim();
const externalImports = new Set();
const included = new Set();
function flatten(file) {
 if (included.has(file)) return '';
 included.add(file);
 return read(file).replace(/@import\s+url\(["']?([^"')]+)["']?\)\s*;/g, (_, url) => {
  if (/^https?:/.test(url)) { externalImports.add(url); return ''; }
  return flatten(url.split('?')[0].replace(/^\//, ''));
 });
}
const css = flatten('styles.20260727-officer-insignia.css') + '\n' + read('trademarks.20260911.css') + '\n' + read('nine-line-brand.20260912.css');
write('site-shared.20260912.css', '/* Generated by scripts/sync-site-shell.cjs; do not hand-edit. */\n' + [...externalImports].map(u => `@import url("${u}");`).join('\n') + '\n' + css);
let count = 0;
for (const file of fs.readdirSync(root).filter(f => f.endsWith('.html'))) {
 let html = read(file);
 if (!html.includes('site-header')) continue;
 const route = file === 'index.html' ? '/' : '/' + file.replace('.html', '');
 let pageHeader = header.replaceAll(`href="${route}"`, `href="${route}" aria-current="page"`);
 if (file === '9-line.html') pageHeader = pageHeader.replaceAll('href="/demo"', 'href="/demo?product=9-line"');
 html = html.replace(/<header\b[^>]*class="site-header[^>]*>[\s\S]*?<\/header>/, pageHeader);
 html = html.replace(/<footer\b[^>]*class="site-footer[^>]*>[\s\S]*?<\/footer>/, footer);
 html = html.replace(/<link\b[^>]*rel="stylesheet"[^>]*>/g, tag => /href="\/(?:styles\.[^"]+|9-line\.20260908-bundle\.css|trademarks\.20260911\.css|nine-line-brand\.20260912\.css|site-(?:shared|ui)\.20260912\.css)"/.test(tag) ? '' : tag);
 html = html.replace(/<link\b[^>]*href="https:\/\/fonts.googleapis.com[^>]*>/g, '');
 html = html.replace('</head>', '<link rel="stylesheet" href="/site-ui.20260912.css">\n</head>');
 html = html.replace(/(<head[^>]*>)/, '$1\n<link rel="stylesheet" href="/site-shared.20260912.css">');
 html = html.replace(/<script src="\/site-ui\.20260912\.js" defer><\/script>\s*/g, '');
 html = html.replace('</body>', '<script src="/site-ui.20260912.js" defer></script>\n</body>');
 html = html.replace(/<p class="hidden-field"[^>]*>/g, '<p class="hidden-field" hidden aria-hidden="true">');
 html = html.replace(/<input\b[^>]*name="company-website"[^>]*>/g, tag => tag.replace(/\s(?:tabindex|autocomplete)="[^"]*"/g, '').replace(/>$/, ' tabindex="-1" autocomplete="off">'));
 html = html.replace(/<input\b[^>]*name="phone"[^>]*>/g, tag => tag.replace(/\s(?:type|inputmode)="[^"]*"/g, '').replace(/>$/, ' type="tel" inputmode="tel">'));
 html = html.replace(/<select\b[^>]*name="(?:role|agency-size|timeline)"[^>]*>(?!<option value="")/g, tag => tag + '<option value="" selected>Select an option (optional)</option>');
 html = html.replace(/<form\b[^>]*data-netlify="true"[^>]*>/g, tag => tag.includes('aria-describedby') ? tag : tag.replace('>', ' aria-describedby="inquiry-instructions">'));
 if (html.includes('data-netlify="true"') && !html.includes('id="inquiry-instructions"')) {
  html = html.replace(/(<form\b[^>]*data-netlify="true"[^>]*>)/, '$1<p class="full-field form-instructions" id="inquiry-instructions">Name, agency and work email are required. Other fields are optional. Do not include case details, protected records or credentials. See our <a href="/privacy">Privacy Policy</a>.</p>');
 }
 if (file === 'demo.html') html = html.replace('<body>', '<body class="demo-page">');
 if (['privacy.html','sms-terms.html','sms-consent.html'].includes(file) && !html.includes('class="on-this-page"')) {
  const links = [];
  html = html.replace(/<h2([^>]*)>([\s\S]*?)<\/h2>/g, (_, attrs, title) => {
   const id = attrs.match(/\bid="([^"]+)"/)?.[1] || `policy-section-${links.length + 1}`;
   links.push(`<li><a href="#${id}">${title}</a></li>`);
   return `<h2${attrs}${/\bid=/.test(attrs) ? '' : ` id="${id}"`}>${title}</h2>`;
  });
  html = html.replace(/(<article[^>]*class="[^"]*content-page[^"]*"[^>]*>)/, `$1<nav class="on-this-page" aria-label="On this page"><strong>On this page</strong><ul>${links.join('')}</ul></nav>`);
 }
 if (['index.html','how-it-works.html'].includes(file)) html = html.replace(/<p>(“(?:La carretera|Mi hijo)[\s\S]*?”)<\/p>/g, '<p lang="es">$1</p>');
 html = html.replace(/(<link rel="canonical" href=")https:\/\/emt\.city919\.com([^\"]*)"/g, '$1https://emt919.com$2"');
 html = html.replace(/(<meta property="og:url" content=")https:\/\/emt\.city919\.com([^\"]*)"/g, '$1https://emt919.com$2"');
 html = html.replace(/[ \t]+(?=\r?$)/gm, '');
 html = html.replace(/(<head[^>]*>)([\s\S]*?)(<\/head>)/, (_, open, body, close) => open + '\n' + body.split(/\r?\n/).filter(line => line.trim()).join('\n') + '\n' + close);
 write(file, html);
 count++;
}
console.log(`Updated ${count} existing page shells; bundled ${included.size} local stylesheets.`);
